let lang = "hu";

function t(key) {
  return (I18N[lang] && I18N[lang][key]) || I18N.hu[key] || key;
}

function applyLang(next) {
  lang = next === "en" ? "en" : "hu";
  document.documentElement.lang = lang;
  try { localStorage.setItem("lang", lang); } catch (_) {}

  document.querySelectorAll("[data-i18n]").forEach((el) => {
    const key = el.getAttribute("data-i18n");
    if (key) el.textContent = t(key);
  });
  document.querySelectorAll("[data-i18n-placeholder]").forEach((el) => {
    const key = el.getAttribute("data-i18n-placeholder");
    if (key) el.setAttribute("placeholder", t(key));
  });
  document.querySelectorAll("[data-i18n-aria]").forEach((el) => {
    const key = el.getAttribute("data-i18n-aria");
    if (key) el.setAttribute("aria-label", t(key));
  });

  const title = t("meta.title");
  document.title = title;
  const desc = t("meta.description");
  setMeta("name", "description", desc);
  setMeta("property", "og:title", title);
  setMeta("property", "og:description", desc);
  setMeta("property", "og:locale", lang === "hu" ? "hu_HU" : "en_US");
  setMeta("name", "twitter:title", title);
  setMeta("name", "twitter:description", desc);

  document.querySelectorAll(".lang button").forEach((btn) => {
    btn.setAttribute("aria-pressed", btn.dataset.lang === lang ? "true" : "false");
  });
}

function setMeta(attr, name, content) {
  let el = document.querySelector(`meta[${attr}="${name}"]`);
  if (el) el.setAttribute("content", content);
}

function initLang() {
  let initial = "hu";
  try {
    const saved = localStorage.getItem("lang");
    if (saved === "en" || saved === "hu") initial = saved;
  } catch (_) {}
  try {
    const q = new URLSearchParams(location.search).get("lang");
    if (q === "en" || q === "hu") initial = q;
  } catch (_) {}
  applyLang(initial);
  document.querySelectorAll(".lang button").forEach((btn) => {
    btn.addEventListener("click", () => applyLang(btn.dataset.lang));
  });
}

function initNav() {
  const header = document.querySelector(".header");
  const toggle = document.querySelector(".nav-toggle");
  if (!toggle || !header) return;
  toggle.addEventListener("click", () => {
    const open = header.classList.toggle("is-open");
    toggle.setAttribute("aria-expanded", open ? "true" : "false");
  });
  header.querySelectorAll(".nav a").forEach((a) => {
    a.addEventListener("click", () => {
      header.classList.remove("is-open");
      toggle.setAttribute("aria-expanded", "false");
    });
  });
}

function initConfigLinks() {
  document.querySelectorAll("[data-smallstep-url]").forEach((a) => {
    a.setAttribute("href", CONFIG.smallstepUrl);
  });
  document.querySelectorAll("[data-smallstep-x]").forEach((a) => {
    a.setAttribute("href", CONFIG.smallstepX);
  });
}

function initForm() {
  const form = document.getElementById("quote-form");
  if (!form) return;
  const err = document.getElementById("form-error");
  form.addEventListener("submit", (e) => {
    e.preventDefault();
    const data = new FormData(form);
    const name = String(data.get("name") || "").trim();
    const email = String(data.get("email") || "").trim();
    const phone = String(data.get("phone") || "").trim();
    const serviceKey = String(data.get("service") || "").trim();
    const message = String(data.get("message") || "").trim();
    if (!name || !email || !serviceKey || !message) {
      if (err) {
        err.hidden = false;
        err.textContent = t("form.error");
      }
      return;
    }
    if (err) err.hidden = true;
    const serviceLabel = t("form.s." + serviceKey) || serviceKey;
    const subject = t("form.subject") + ": " + serviceLabel;
    const lines = [
      t("form.body.intro") + ".",
      "",
      t("form.body.name") + ": " + name,
      t("form.body.email") + ": " + email,
      t("form.body.phone") + ": " + (phone || "-"),
      t("form.body.service") + ": " + serviceLabel,
      "",
      t("form.body.message") + ":",
      message,
    ];
    const href =
      "mailto:" +
      CONFIG.email +
      "?subject=" +
      encodeURIComponent(subject) +
      "&body=" +
      encodeURIComponent(lines.join("\n"));
    window.location.href = href;
  });
}

function initReveal() {
  const nodes = document.querySelectorAll(".reveal");
  if (!nodes.length) return;
  if (window.matchMedia("(prefers-reduced-motion: reduce)").matches) {
    nodes.forEach((n) => n.classList.add("is-in"));
    return;
  }
  const io = new IntersectionObserver(
    (entries) => {
      entries.forEach((entry) => {
        if (entry.isIntersecting) {
          entry.target.classList.add("is-in");
          io.unobserve(entry.target);
        }
      });
    },
    { threshold: 0.12, rootMargin: "0px 0px -8% 0px" }
  );
  nodes.forEach((n) => io.observe(n));
}

function initStars() {
  const canvas = document.getElementById("stars");
  if (!canvas || !canvas.getContext) return;
  const ctx = canvas.getContext("2d");
  let stars = [];
  let width = 0;
  let height = 0;

  function resize() {
    const dpr = Math.min(window.devicePixelRatio || 1, 2);
    width = window.innerWidth;
    height = window.innerHeight;
    canvas.width = Math.floor(width * dpr);
    canvas.height = Math.floor(height * dpr);
    canvas.style.width = width + "px";
    canvas.style.height = height + "px";
    ctx.setTransform(dpr, 0, 0, dpr, 0, 0);
    const count = Math.max(40, Math.floor((width * height) / 14000));
    stars = Array.from({ length: count }, () => ({
      x: Math.random() * width,
      y: Math.random() * height,
      r: Math.random() * 1.15 + 0.15,
      a: Math.random() * 0.45 + 0.08,
    }));
    draw();
  }

  function draw() {
    ctx.clearRect(0, 0, width, height);
    for (const s of stars) {
      ctx.fillStyle = "rgba(255,255,255," + s.a + ")";
      ctx.beginPath();
      ctx.arc(s.x, s.y, s.r, 0, Math.PI * 2);
      ctx.fill();
    }
  }

  resize();
  window.addEventListener("resize", resize, { passive: true });
}

document.addEventListener("DOMContentLoaded", () => {
  initConfigLinks();
  initLang();
  initNav();
  initForm();
  initReveal();
  initStars();
});
